#[test]
fn motif_golden() {
    for g in GOLDEN {
        let p = Profile::derive(g.psk.as_bytes());
        assert_eq!(p.motif.mode, g.mode, "{} mode", g.psk);

        let non_salt: Vec<u8> = p
            .region
            .iter()
            .enumerate()
            .filter(|(i, _)| !p.perm.contains(&(*i as u8)))
            .map(|(_, b)| *b)
            .collect();
        assert_eq!(hex::encode(non_salt), g.region, "{} region", g.psk);

        let mut aad0 = vec![0; p.header_aad_len(0)];
        p.motif.fill(0, &mut aad0);
        assert_eq!(hex::encode(aad0), g.aad0, "{} aad0", g.psk);

        let mut aad1 = vec![0; p.header_aad_len(1)];
        p.motif.fill(1, &mut aad1);
        assert_eq!(hex::encode(aad1), g.aad1, "{} aad1", g.psk);

        let mut pad3 = [0; 64];
        p.motif.fill(3, &mut pad3);
        assert_eq!(hex::encode(pad3), g.pad3, "{} pad3", g.psk);
    }
}
